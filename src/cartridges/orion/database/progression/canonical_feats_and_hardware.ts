interface LoreFeatSeed {
  id: string;
  name: string;
  lineageHint: string;
  tier: FeatTier;
  kind?: 'system' | 'interface';
  skill: PilotSkillId;
  cat: FeatSynergyCategory;
  reqEq: string;
  effect: string;
  status?: string;
  gems: [GemId, GemId];
  loadStepUp?: number;
  modifiers?: FrameFeatDefinition['modifiers'];
}

const TIER_LEVEL_MAP: Record<FeatTier, number> = {
  I: 2,
  II: 5,
  III: 9,
  IV: 14,
  V: 18,
};

function buildLoreFeat(s: LoreFeatSeed): FrameFeatDefinition {
  const gemCount1 = s.tier === 'IV' || s.tier === 'V' ? 2 : 1;
  const statusSuffix = s.status && s.status !== '—' ? ` [${s.status}]` : '';
  const reqLabel = s.reqEq && s.reqEq !== '—' ? s.reqEq : 'Any Loadout';
  return {
    id: s.id,
    name: s.name,
    tier: s.tier,
    kind: s.kind || (s.loadStepUp ? 'system' : 'interface'),
    requiredSkillId: s.skill,
    requiredSkillLevel: TIER_LEVEL_MAP[s.tier],
    synergyCategory: s.cat,
    requiredEquipment: reqLabel,
    gainDescription: `${s.effect}${statusSuffix}`,
    costDescription: `Requirement: ${reqLabel} (${s.lineageHint} affinity)`,
    gemSockets: [
      { gemId: s.gems[0], count: gemCount1 },
      { gemId: s.gems[1], count: 1 },
    ],
    unlocksDescription: `Requires: ${reqLabel}`,
    loadStepUp: s.loadStepUp,
    modifiers: s.modifiers || { damageMult: 1.08 },
  };
}

